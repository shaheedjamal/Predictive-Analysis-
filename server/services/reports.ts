import { jsPDF } from 'jspdf';
import Papa from 'papaparse';

export interface PredictionReportPayload {
  prediction_code: string;
  created_at: string;
  researcher_name: string;
  compound_name: string;
  original_smiles: string;
  canonical_smiles: string;
  molecular_formula: string;
  descriptors: {
    molecular_weight: number;
    logp: number;
    tpsa: number;
    hbd: number;
    hba: number;
    rotatable_bonds: number;
    ring_count: number;
    heavy_atoms?: number;
    lipinski_violations?: number;
  };
  context: {
    assay_type: string;
    target_name: string;
    biological_model: string;
    organism: string;
    endpoint: string;
    exposure_duration?: string;
  };
  model: {
    name: string;
    algorithm: string;
    version: string;
    split_method: string;
    mae: number;
    rmse: number;
    r2: number;
    is_demo: boolean;
  };
  predicted_value: number;
  predicted_unit: string;
  in_domain: boolean;
  domain_distance: number;
  applicability_warning: string | null;
  is_demo: boolean;
}

export function generatePredictionPdfBuffer(data: PredictionReportPayload): Buffer {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 44;

  // Header bar
  doc.setFillColor(11, 18, 33);
  doc.rect(0, 0, pageWidth, 72, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('DrugEfficacy Insight — Research Decision-Support Report', 40, 34);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(148, 163, 184);
  doc.text(
    `Prediction ID: ${data.prediction_code}   |   Generated: ${data.created_at}   |   Researcher: ${data.researcher_name}`,
    40,
    54
  );

  y = 94;

  if (data.is_demo || data.model.is_demo) {
    doc.setFillColor(254, 243, 199);
    doc.setDrawColor(217, 119, 6);
    doc.rect(40, y, pageWidth - 80, 32, 'FD');
    doc.setTextColor(146, 64, 14);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.text(
      'DEMO MODE WARNING: Estimate generated by a model trained on synthetic demonstration data.',
      50,
      y + 20
    );
    y += 46;
  }

  const sectionTitle = (title: string) => {
    doc.setTextColor(15, 23, 42);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.text(title, 40, y);
    y += 6;
    doc.setDrawColor(203, 213, 225);
    doc.line(40, y, pageWidth - 40, y);
    y += 14;
  };

  const kvRow = (label: string, value: string) => {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9.5);
    doc.setTextColor(71, 85, 105);
    doc.text(label, 44, y);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(15, 23, 42);
    const wrapped = doc.splitTextToSize(value, pageWidth - 220);
    doc.text(wrapped, 190, y);
    y += Math.max(15, wrapped.length * 13);
  };

  // Predicted Endpoint Highlight
  sectionTitle('1. Estimated Research Endpoint');
  kvRow('Estimated Value:', `${data.predicted_value.toFixed(4)} ${data.predicted_unit} (${data.context.endpoint})`);
  kvRow('Applicability Domain:', data.in_domain ? `In-domain (RMS z-distance: ${data.domain_distance})` : `WARNING — Out of domain (RMS z=${data.domain_distance})`);
  if (data.applicability_warning) {
    kvRow('Domain Notes:', data.applicability_warning);
  }
  y += 6;

  sectionTitle('2. Compound & Structural Representation');
  kvRow('Compound Name:', data.compound_name || 'Unnamed Query Compound');
  kvRow('Molecular Formula:', data.molecular_formula || 'N/A');
  kvRow('Original SMILES:', data.original_smiles);
  kvRow('Canonical SMILES:', data.canonical_smiles);
  y += 6;

  sectionTitle('3. Computed Molecular Descriptors');
  kvRow('Molecular Weight:', `${data.descriptors.molecular_weight} Da`);
  kvRow('Calculated LogP:', `${data.descriptors.logp}`);
  kvRow('TPSA:', `${data.descriptors.tpsa} A^2`);
  kvRow('H-Bond Donors / Acceptors:', `${data.descriptors.hbd} donors / ${data.descriptors.hba} acceptors`);
  kvRow('Rotatable Bonds / Rings:', `${data.descriptors.rotatable_bonds} rotatable / ${data.descriptors.ring_count} rings`);
  y += 6;

  sectionTitle('4. Experimental & Biological Context');
  kvRow('Assay Type:', data.context.assay_type);
  kvRow('Target Name:', data.context.target_name);
  kvRow('Biological Model:', data.context.biological_model);
  kvRow('Organism:', data.context.organism);
  kvRow('Exposure Duration:', data.context.exposure_duration || 'Not specified');
  y += 6;

  sectionTitle('5. Model Provenance & Validation Metrics');
  kvRow('Model Name / Version:', `${data.model.name} (${data.model.version})`);
  kvRow('Algorithm:', data.model.algorithm);
  kvRow('Evaluation Split:', data.model.split_method);
  kvRow('Measured Test Metrics:', `MAE: ${data.model.mae} | RMSE: ${data.model.rmse} | R^2: ${data.model.r2}`);
  y += 10;

  // Limitations & Disclaimer Box
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(203, 213, 225);
  doc.rect(40, y, pageWidth - 80, 68, 'FD');
  doc.setTextColor(30, 41, 59);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.text('LIMITATIONS & RESEARCH-ONLY DISCLAIMER', 50, y + 16);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  const disclaimer =
    'This report is generated by DrugEfficacy Insight strictly as a computational research and educational decision-support prototype. ' +
    'It is NOT a medical device, clinical diagnostic, or prescribing tool. Model estimates depend on training dataset coverage, assay ' +
    'consistency, and applicability domain, and must never be interpreted as proof of pharmacological efficacy or clinical safety.';
  const wrappedDisc = doc.splitTextToSize(disclaimer, pageWidth - 100);
  doc.text(wrappedDisc, 50, y + 30);

  const arrayBuffer = doc.output('arraybuffer');
  return Buffer.from(arrayBuffer);
}

export function generatePredictionCsv(data: PredictionReportPayload): string {
  return Papa.unparse([
    {
      prediction_id: data.prediction_code,
      timestamp: data.created_at,
      researcher: data.researcher_name,
      compound_name: data.compound_name,
      original_smiles: data.original_smiles,
      canonical_smiles: data.canonical_smiles,
      molecular_formula: data.molecular_formula,
      molecular_weight: data.descriptors.molecular_weight,
      logp: data.descriptors.logp,
      tpsa: data.descriptors.tpsa,
      hbd: data.descriptors.hbd,
      hba: data.descriptors.hba,
      rotatable_bonds: data.descriptors.rotatable_bonds,
      ring_count: data.descriptors.ring_count,
      assay_type: data.context.assay_type,
      target_name: data.context.target_name,
      biological_model: data.context.biological_model,
      organism: data.context.organism,
      endpoint: data.context.endpoint,
      exposure_duration: data.context.exposure_duration ?? '',
      predicted_value: data.predicted_value,
      predicted_unit: data.predicted_unit,
      model_name: data.model.name,
      model_version: data.model.version,
      model_mae: data.model.mae,
      model_rmse: data.model.rmse,
      model_r2: data.model.r2,
      in_domain: data.in_domain,
      domain_distance: data.domain_distance,
      applicability_warning: data.applicability_warning ?? '',
      is_demo: data.is_demo,
      disclaimer: 'Research & educational prototype only; not proof of efficacy or safety.',
    },
  ]);
}
